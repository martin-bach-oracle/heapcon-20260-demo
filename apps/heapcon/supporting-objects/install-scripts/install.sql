create table documentation_tab (
    id             number generated by default on null as identity,
    document_title varchar2(255),
    document_hash  varchar2(64),
    filename       varchar2(255),
    mime_type      varchar2(255),
    updated_at     date,
    data           blob
);

alter table documentation_tab add constraint pk_documentation_tab primary key ( id );

alter table documentation_tab add constraint uk_doc_hash unique ( document_hash );

create table doc_chunks (
    doc_id          number,
    chunk_id        number,
    chunk_data      varchar2(4000),
    chunk_embedding vector
);

alter table doc_chunks add constraint pk_doc_chunks primary key ( chunk_id );

alter table doc_chunks add constraint fk_chunk_doc foreign key ( doc_id )
    references documentation_tab;

create index i_fk_chunk_doc on
    doc_chunks (
        doc_id
    );

create or replace package documentation_chunker as
    procedure rebuild_all (
        p_embedding_model in varchar2
    );
end documentation_chunker;
/

create or replace package body documentation_chunker as

    procedure rebuild_all (
        p_embedding_model in varchar2
    ) is
        l_embedding_params varchar2(4000);
    begin
        if p_embedding_model is null then
            raise_application_error(
                -20001,
                'An in-database embedding model name is required.'
            );
        end if;

        -- Build the database-provider parameters for UTL_TO_EMBEDDINGS.
        select
            json_object(
                'provider' value 'database',
                        'model' value p_embedding_model
            returning varchar2(4000))
          into l_embedding_params
          from dual;

        -- Full refresh: no delta or per-document preservation.
        delete from doc_chunks;

        insert into doc_chunks (
            doc_id,
            chunk_id,
            chunk_data,
            chunk_embedding
        )
            select d.id,
                   row_number()
                   over(
                        order by d.id,
                                 jt.embed_id
                   ) as chunk_id,
                   jt.embed_data,
                   to_vector(jt.embed_vector) as chunk_embedding
              from documentation_tab d,
                   dbms_vector_chain.utl_to_embeddings(
                       dbms_vector_chain.utl_to_chunks(
                           dbms_vector_chain.utl_to_text(d.data),
                           json('{ "normalize": "all" }')
                       ),
                       json(l_embedding_params)
                   ) e,
                   json_table ( e.column_value,'$[*]'
                       columns (
                           embed_id number path '$.embed_id',
                           embed_data varchar2 ( 4000 ) path '$.embed_data',
                           embed_vector clob path '$.embed_vector'
                       )
                   )
               jt
             where d.data is not null;

    exception
        when others then
            -- Undo the delete and any partial inserts, then pass the error back.
            rollback to doc_chunks_rebuild;
            raise;
    end rebuild_all;

end documentation_chunker;
/

create view knowledge_search as
    select c.chunk_id,
           c.chunk_data,
           c.chunk_embedding,
           t.document_title
      from doc_chunks c
      left join documentation_tab t
    on ( c.doc_id = t.id );